 await expect(page.getByRole('link',{name:'Abrir prévia do post 2',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Detalhes do post 2',exact:true}).click()
 await expect(page).toHaveURL(/\/conteudos\/2$/)
