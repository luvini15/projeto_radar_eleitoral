import {chromium,expect as baseExpect} from '@playwright/test'
const expect=baseExpect.configure({timeout:30000})
const base=process.env.UI_BASE_URL||'http://localhost:5175'
const api=process.env.UI_API_URL||'http://127.0.0.1:8011'
const browser=await chromium.launch()
const errors=[]
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('https://**/*',r=>r.abort())
 await page.route('**/api/campaigns/*/posts/*/thumbnail*',r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400"><rect width="400" height="400" fill="#222"/></svg>'}))
 await page.goto(base+'/visao-geral',{waitUntil:'domcontentloaded',timeout:60000})
 await expect(page.getByRole('heading',{name:'Campanha de teste isolado',exact:true})).toBeVisible({timeout:60000})
 await expect(page.getByRole('link',{name:'Visão Geral',exact:true}).first()).toBeVisible()
 await page.getByRole('combobox',{name:'Chapa',exact:true}).selectOption('1')
 await expect(page.getByRole('heading',{name:'Chapa A - teste',exact:true})).toBeVisible()
 console.log('PASS: executive route and global slate selection')
 await page.screenshot({path:'tmp-slate-executive-desktop.png',fullPage:true})
 await page.goto(base+'/conteudos',{waitUntil:'domcontentloaded'})
 await expect(page.locator('article')).toHaveCount(10,{timeout:30000})
 await expect(page.getByText('fixture_perfil_3',{exact:false})).toHaveCount(0)
 await page.getByRole('combobox',{name:'Perfil da análise',exact:true}).selectOption('1')
 await expect(page.locator('article')).toHaveCount(5)
 console.log('PASS: content origin and subordinate profile filter')
 await page.goto(base+'/audiencia',{waitUntil:'domcontentloaded'})
 await expect(page.locator('.recharts-line')).toHaveCount(1,{timeout:30000})
 await page.getByRole('combobox',{name:'Chapa',exact:true}).selectOption('2')
 await expect(page.getByText('Dados insuficientes',{exact:true})).toBeVisible()
 await expect(page.locator('.recharts-line')).toHaveCount(0)
 await page.getByRole('combobox',{name:'Nível da audiência'}).selectOption('profile')
 await expect(page.getByText('São necessárias pelo menos duas coletas comparáveis para calcular evolução.')).toBeVisible()
 console.log('PASS: complete-date follower aggregation and single-collection empty state')
 await page.goto(base+'/concorrentes',{waitUntil:'domcontentloaded'})
 await expect(page.getByText('Comparação entre chapas',{exact:true}).last()).toBeVisible({timeout:30000})
 await page.getByRole('combobox',{name:'Chapa',exact:true}).selectOption('')
 await page.getByRole('combobox',{name:'Nível da comparação'}).selectOption('profiles')
 await expect(page.locator('.recharts-bar-rectangle').first()).toBeVisible({timeout:30000})
 await expect(page.getByRole('checkbox',{name:'Escala de raiz quadrada'})).toBeChecked()
 const daily=page.getByRole('img',{name:'Desempenho por dia: Interações'})
 await expect(daily.locator('.recharts-bar-rectangle').first()).toBeVisible()
 await daily.locator('.recharts-bar-rectangle').first().hover({force:true})
 await expect(daily.locator('.recharts-tooltip-wrapper')).toBeVisible()
 await expect(page.locator('.recharts-scatter-symbol').first()).toBeVisible()
 console.log('PASS: independent profile comparison, daily bars, outlier scale and tooltips')
 await page.goto(base+'/configuracoes',{waitUntil:'domcontentloaded'})
 await expect(page.getByRole('button',{name:'Criar chapa',exact:true})).toBeEnabled({timeout:30000})
 const newCard=page.getByRole('region',{name:'Chapa Chapa C - teste',exact:true})
 if(!await newCard.count()){
  await page.locator('input[name=slateName]').fill('Chapa C - teste')
  await page.getByRole('button',{name:'Criar chapa',exact:true}).click()
 }
 await expect(newCard).toBeVisible()
 await newCard.getByRole('button',{name:'+ Adicionar perfil',exact:true}).click()
 await page.getByRole('combobox',{name:'Perfil para Chapa C - teste'}).selectOption('5')
 await page.getByRole('combobox',{name:'Posição em Chapa C - teste'}).selectOption('CANDIDATE')
 await newCard.getByRole('button',{name:'Associar perfil',exact:true}).click()
 await expect(newCard.getByText('@fixture_perfil_5',{exact:true})).toBeVisible()
 const section=newCard
 const before=await (await page.request.get(api+'/api/campaigns/1/posts')).json()
 await section.getByRole('button',{name:'Desvincular',exact:true}).click()
 await page.getByRole('textbox',{name:'Confirmação da operação'}).fill('fixture_perfil_5')
 await page.getByRole('button',{name:'Confirmar desvinculação',exact:true}).click()
 await expect(section.getByRole('button',{name:'Desvincular',exact:true})).toHaveCount(0)
 const after=await (await page.request.get(api+'/api/campaigns/1/posts')).json()
 expect(after.total_posts).toBe(before.total_posts)
 console.log('PASS: slate creation, assignment and unlinking preserve posts')
 console.log('Waiting for the real API rate-limit window before mobile navigation')
 await page.waitForTimeout(60000)
 for(const route of ['/visao-geral','/conteudos','/temas-formatos','/dias-horarios','/audiencia','/concorrentes','/coletas','/tendencias','/relatorios','/inteligencia-territorial','/configuracoes']) {
  await page.setViewportSize({width:390,height:844})
  await page.goto(base+route,{waitUntil:'domcontentloaded'})
  await expect(page.locator('main')).toBeVisible()
  await page.waitForTimeout(250)
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)
  if(overflow)throw Error('Horizontal overflow: '+route)
 }
 await page.goto(base+'/visao-geral',{waitUntil:'domcontentloaded'})
 await expect(page.getByRole('heading',{name:'Campanha de teste isolado',exact:true})).toBeVisible()
 await page.screenshot({path:'tmp-slate-executive-mobile.png',fullPage:true})
 expect(errors).toEqual([])
 console.log('PASS: all analysis routes on mobile without horizontal overflow or runtime errors')
} finally {await browser.close()}
