import {chromium,expect as baseExpect} from '@playwright/test'
const expect=baseExpect.configure({timeout:45000})
const base=process.env.UI_BASE_URL||'http://localhost:5173'
const browser=await chromium.launch()
const errors=[],bad=[]
try{
 const page=await browser.newPage({viewport:{width:1440,height:1050}})
 page.on('pageerror',e=>errors.push(e.message))
 page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=400&&!r.url().includes('/thumbnail'))bad.push(r.status()+' '+new URL(r.url()).pathname)})
 await page.route('https://**/*',r=>r.abort())
 await page.route('**/api/campaigns/*/posts/*/thumbnail*',r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200"/>'}))
 await page.goto(base+'/visao-geral',{waitUntil:'domcontentloaded'})
 await page.getByRole('combobox',{name:'Campanha',exact:true}).selectOption('3')
 await page.getByRole('combobox',{name:'Chapa',exact:true}).selectOption('')
 await page.getByRole('combobox',{name:'Período analisado',exact:true}).selectOption('15')
 await expect(page.getByRole('combobox',{name:'Período analisado',exact:true})).toHaveValue('15')
 await page.getByRole('combobox',{name:'Período analisado',exact:true}).selectOption('custom')
 await page.getByLabel('Início do período',{exact:true}).fill('2026-10-21')
 await page.getByLabel('Fim do período',{exact:true}).fill('2026-10-05')
 await expect(page.getByRole('button',{name:'Aplicar período',exact:true})).toBeDisabled()
 await page.getByLabel('Início do período',{exact:true}).fill('2026-10-05')
 await page.getByLabel('Fim do período',{exact:true}).fill('2026-10-21')
 await page.getByRole('button',{name:'Aplicar período',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Evolução de seguidores · chapas e perfis',exact:true})).toBeVisible()
 const first=page.getByRole('combobox',{name:'Análise comparada',exact:true}).first()
 await expect(first).toHaveValue('followers')
 await expect(page.locator('.recharts-line-curve').first()).toBeVisible()
 await page.getByText('Valores exatos da comparação',{exact:true}).first().click()
 await expect(page.getByRole('cell',{name:'350.773',exact:true}).first()).toBeVisible()
 await expect(page.getByRole('cell',{name:'363.391',exact:true}).first()).toBeVisible()
 await expect(page.getByRole('cell',{name:'147.816',exact:true}).first()).toBeVisible()
 await expect(page.getByRole('cell',{name:'171.929',exact:true}).first()).toBeVisible()
 await page.locator('.recharts-line-dot').first().hover({force:true})
 await expect(page.getByText('Histórico manual',{exact:true}).first()).toBeVisible()
 console.log('PASS: 15 days, validated custom calendar, exact manual slate totals and source tooltip')
 await page.getByRole('combobox',{name:'Chapa',exact:true}).selectOption({label:'Chapa Celina'})
 await expect(page.getByRole('combobox',{name:'Perfil global',exact:true}).getByRole('option')).toHaveCount(3)
 const names=await page.getByRole('combobox',{name:'Perfil global',exact:true}).locator('option').allTextContents()
 expect(names).toEqual(['Todos os perfis da seleção','@celinaleao','@gustavo.rochadf'])
 await expect(page.getByRole('combobox',{name:'Modo de comparação',exact:true}).first()).toHaveValue('profiles')
 await first.selectOption('summary')
 await page.getByRole('combobox',{name:'Métrica comparada',exact:true}).first().selectOption('posts')
 await page.getByRole('combobox',{name:'Tipo do gráfico',exact:true}).first().selectOption('pie')
 await expect(page.locator('.recharts-pie-sector').first()).toBeVisible()
 await page.getByRole('combobox',{name:'Métrica comparada',exact:true}).first().selectOption('avg_observed_interactions')
 await expect(page.getByRole('combobox',{name:'Tipo do gráfico',exact:true}).first()).toHaveValue('bars')
 await expect(page.getByRole('combobox',{name:'Tipo do gráfico',exact:true}).first().locator('option[value=pie]')).toHaveAttribute('disabled','')
 await first.selectOption('daily')
 await expect(page.getByRole('combobox',{name:'Tipo do gráfico',exact:true}).first()).toHaveValue('line')
 await expect(page.getByText('Totais observados por data de publicação (UTC), usando o último snapshot. Não representa interações novas recebidas naquele dia.',{exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'Perfil global',exact:true}).selectOption({label:'@celinaleao'})
 await expect(page.getByRole('heading',{name:'Evolução de seguidores · chapas e perfis',exact:true})).toBeVisible()
 await expect(page.getByRole('combobox',{name:'Modo de comparação',exact:true}).first()).toHaveValue('profiles')
 console.log('PASS: subordinate profile scope, profile comparison, pie restrictions, metric changes and daily semantics')
 await page.getByRole('combobox',{name:'Perfil global',exact:true}).selectOption('')
 await expect(page.locator('.recharts-line-curve').first()).toBeVisible()
 await page.screenshot({path:'tmp-temporal-desktop.png',fullPage:true})
 console.log('Waiting for the real API rate-limit window before route coverage')
 await page.waitForTimeout(60000)
 for(const route of ['/visao-geral','/conteudos','/temas-formatos','/dias-horarios','/audiencia','/coletas','/concorrentes','/tendencias','/relatorios','/inteligencia','/configuracoes']){
  await page.goto(base+route,{waitUntil:'domcontentloaded'})
  await expect(page.getByRole('heading',{level:1})).toBeVisible()
  if(route==='/relatorios'){await expect(page.getByLabel('Data inicial do relatório',{exact:true})).toHaveValue('2026-10-05')}else if(route!=='/configuracoes'){await expect(page.getByRole('combobox',{name:'Período analisado',exact:true})).toHaveValue('custom');await expect(page.getByLabel('Início do período',{exact:true})).toHaveValue('2026-10-05')}
  await page.waitForTimeout(650)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),route).toBe(false)
 }
 console.log('PASS: 11 routes keep the shared custom period, campaign/slate/profile hierarchy and no horizontal overflow')
 for(const width of [768,390]){
  await page.setViewportSize({width,height:900})
  await page.goto(base+'/visao-geral',{waitUntil:'domcontentloaded'})
  await expect(page.getByRole('heading',{name:'Evolução de seguidores · chapas e perfis',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)).toBe(false)
  await expect(page.locator('.recharts-line-curve').first()).toBeVisible()
  await page.screenshot({path:'tmp-temporal-'+width+'.png',fullPage:true})
 }
 expect(errors).toEqual([]);expect(bad).toEqual([])
 console.log('PASS: desktop, 768px and 390px, no runtime errors or failing API calls')
}finally{await browser.close()}
