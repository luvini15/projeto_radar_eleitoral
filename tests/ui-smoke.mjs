import { chromium, expect } from '@playwright/test'
const browser = await chromium.launch({headless:true})
const page = await browser.newPage()
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
await page.addInitScript(()=>sessionStorage.setItem('data-sight:session-simulada',JSON.stringify({nome:'Teste',email:'test@example.com',papel:'Administrador'})))
await page.route('**/api/**',async route=>{
 const url=new URL(route.request().url()); url.port='8001'
 const response=await route.fetch({url:url.toString()})
 await route.fulfill({response})
})
await page.clock.install()
await page.goto('http://localhost:5173/')
await expect(page.getByRole('heading',{name:'Último post',exact:true})).toBeVisible()
await expect(page.getByText('12 publicações de 1 perfil acompanhadas nesta leitura.',{exact:false})).toBeVisible()
const latestPost = page.getByRole('article',{name:'Último post do perfil'})
await expect(latestPost.getByText('Imagem',{exact:true})).toBeVisible()
await expect(latestPost.getByText('Curtidas',{exact:true}).locator('..').getByText('—',{exact:true})).toBeVisible()
await expect(latestPost.getByText('Comentários',{exact:true}).locator('..').getByText('0',{exact:true})).toBeVisible()
const refreshed = page.waitForResponse(response => response.url().includes('/overview?limit=25') && response.status() === 200)
await page.clock.fastForward(61_000)
await refreshed
await expect(page.getByRole('heading',{name:'Último post',exact:true})).toBeVisible()
await page.getByLabel('Posts recentes por perfil').selectOption('10')
